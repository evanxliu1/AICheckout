// Builds the catalog v3 deterministically from the agent-verified corpora and overlays, never from model output.
//
//   node scripts/build-catalog-v3.mjs            write packages/rewards-core/src/catalog-v3.ts, the build report and
//                                                the rule-ID ledger
//   node scripts/build-catalog-v3.mjs --check    fail if any of the three committed files is stale (CI)
//   node scripts/build-catalog-v3.mjs --config <file> --out-dir <dir>
//                                                a proposed build (pipeline run build --proposed): the catalog of another
//                                                build config, written to <dir> as catalog-v3.json, the build report and
//                                                ledger-diff.json; the committed catalog, report and ledger are not written
//
// Inputs: the layers of evals/curation/catalog-batches.json (the frozen base layer, evals/curation/expansion and
// evals/curation/real, then the pipeline batches in evals/curation/batches/), merged by scripts/lib/catalog-batches.mjs,
// and the rule-ID ledger evals/curation/rule-id-ledger.json. The build itself is scripts/lib/catalog-v3.mjs; the real
// cards are checked against release 1 (CATALOG_V2). The version comes from the config (bump the counter for a rebuild
// from the same captures); the dates come from the capture manifests and the freshness records in
// evals/curation/freshness/ (see `catalogDates`, `effectiveSources`). A real card a pipeline batch replaced is not
// checked against release 1 (it keeps the release-1 names and rule-ID scheme; continuity applies). A version in the config's
// `publishedVersions` is refused, before anything is written, unless the build has its ledger rule IDs and terms.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { format, resolveConfig } from 'prettier';
import { CATALOG_V2 } from '../packages/rewards-core/src/catalog-v2.ts';
import { BATCHES_CONFIG_PATH, loadCatalogBatches, mergeLayers } from './lib/catalog-batches.mjs';
import {
  CATALOG_V3_BYTE_BUDGET,
  QUOTE_LIMIT_OMISSIONS,
  buildRelease,
  catalogStats,
  checkRealCards,
  emptyLedger,
  ledgerText,
  updateLedger,
} from './lib/catalog-v3.mjs';
import { CATALOG_V3_LIMITS } from '../packages/rewards-core/src/schema.ts';

const { values: args } = parseArgs({
  options: {
    check: { type: 'boolean', default: false },
    config: { type: 'string', default: BATCHES_CONFIG_PATH },
    'out-dir': { type: 'string' },
  },
});
const root = new URL('../', import.meta.url);
const proposedDir = args['out-dir'] ? new URL(`${args['out-dir'].replace(/\/?$/, '/')}`, root) : null;
const out = new URL('packages/rewards-core/src/catalog-v3.ts', root);
const reportOut = proposedDir
  ? new URL('catalog-build-report.md', proposedDir)
  : new URL('evals/curation/expansion/catalog-build-report.md', root);
const ledgerOut = new URL('evals/curation/rule-id-ledger.json', root);

const readLedger = () => {
  try {
    return JSON.parse(readFileSync(ledgerOut, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return emptyLedger();
    throw error;
  }
};
const loaded = await loadCatalogBatches(fileURLToPath(root), args.config);
const inputs = { ...mergeLayers(loaded), ledger: readLedger() };
const { catalog, dates, continuity } = buildRelease(inputs);
// Real cards a pipeline batch replaced carry the batch's terms: only the others are pinned to release 1.
const replacedReal = new Set(inputs.replacedReal);
const realProblems = checkRealCards(catalog, CATALOG_V2, { replaced: inputs.replacedReal });
if (realProblems.length) {
  console.error(`The real cards differ from release 1:\n- ${realProblems.join('\n- ')}`);
  process.exit(1);
}
let updatedLedger;
try {
  updatedLedger = updateLedger(inputs.ledger, catalog, { published: loaded.config.publishedVersions });
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
const ledger = ledgerText(updatedLedger);
const stats = catalogStats(catalog);

const header = `// Generated by scripts/build-catalog-v3.mjs from the agent-verified corpora (evals/curation/expansion/corpus.json,
// evals/curation/real/corpus.v2.json), reward-programs.json, merchants.json and catalog-overlay.json.
// Do not edit; rerun \`npm run catalog:v3\`. Build report: evals/curation/expansion/catalog-build-report.md.
import type { CatalogV3 } from './types.ts';

/** The ${catalog.cards.length}-card catalog (schema 3), built from agent-verified labels of issuer pages captured
 * ${dates.captureDates.join(', ').replace(/, ([^,]*)$/, ' and $1')} and the verified catalog overlay. Covers ${catalog.merchants.map((m) => m.name).join(', ')}. */
export const CATALOG_V3: CatalogV3 = ${JSON.stringify(catalog)};
`;
const text = await format(header, { ...(await resolveConfig(out.pathname)), filepath: out.pathname });

const pct = (bytes) => `${((bytes / CATALOG_V3_LIMITS.bytes) * 100).toFixed(1)}%`;
const n = (value) => value.toLocaleString('en-US');
const overlay = inputs.overlay;
const corpusIds = new Set(inputs.corpora[0].cases.map((item) => item.cardId));
const dropped = inputs.dropped;
const table = (head, rows) =>
  [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
const programRows = Object.entries(stats.programsByBasis)
  .sort()
  .map(([basis, count]) => [
    basis,
    String(count),
    String(stats.cardsByBasis[basis] ?? 0),
    catalog.programs
      .filter((p) => p.valuation.basis === basis)
      .map((p) => `\`${p.id}\``)
      .join(', '),
  ]);
const report = `# Catalog v3 build report

Generated by \`npm run catalog:v3\` (\`scripts/build-catalog-v3.mjs\`); \`npm run catalog:v3:check\` fails when this file
or \`packages/rewards-core/src/catalog-v3.ts\` is stale. Do not edit by hand.

- **Version** \`${catalog.version}\`, verified ${catalog.verifiedAt}, expires ${catalog.expiresAt} (30 days, the
  contract maximum). Real-card sources were captured 2026-09-29, expansion sources 2026-10-02, merchant sources
  2026-09-28; published estimates were read 2026-10-02 (inside the window from 30 days before verification to
  expiry).
- **Inputs** \`expansion/corpus.json\` (${inputs.corpora[0].version}, ${corpusIds.size} cards), \`real/corpus.v2.json\`
  (${inputs.corpora[1].version}, 7 cards), \`reward-programs.json\` (${inputs.rewardPrograms.version}),
  \`merchants.json\`, \`catalog-overlay.json\` (${overlay.version}). All labels and overlay decisions are
  agent-verified, not human-verified.
- **Real cards** keep release 1's names, rule IDs, wording, rates, caps, activation, U.S.-only flags, excluded
  payment paths, end dates, sources and exclusions (checked against \`CATALOG_V2\` \`${CATALOG_V2.version}\` on every
  build). All seven earn cash back: Double Cash's terms state a percentage cash back (paid as ThankYou Points), so it
  maps to the \`cash-back\` program under general rule 1 (coordinator decision 2026-10-03); release 1's points at a stated
  1¢ give the same cents. The version stays \`${catalog.version}\` after this change: it was not yet published, so
  no extension or release holds the earlier contents.${
    replacedReal.size
      ? `\n- **Real cards refreshed by a batch** (release-1 names and rule-ID prefixes kept; not checked against release 1,
  rule-ID continuity below applies): ${[...replacedReal].map((id) => `\`${id}\``).join(', ')}.`
      : ''
  }

## Size

| Measure | Bytes | Share of 1 MiB | Budget (75%) |
| --- | --- | --- | --- |
| JSON (\`catalogV3Schema\`) | ${n(stats.jsonBytes)} | ${pct(stats.jsonBytes)} | ${n(CATALOG_V3_BYTE_BUDGET)} |
| JSONB text (\`valid_catalog_v3\`, computed) | ${n(stats.jsonbTextBytes)} | ${pct(stats.jsonbTextBytes)} | ${n(CATALOG_V3_BYTE_BUDGET)} |

## Counts

| Item | Count |
| --- | --- |
| Cards | ${stats.cards} (${catalog.cards.length - 7} expansion, 7 real) |
| Rules | ${stats.rules} (at most ${stats.maxRulesPerCard} per card) |
| Sources | ${stats.sources} |
| Programs | ${stats.programs} (${stats.storeCreditPrograms} with redemption brands) |
| Brands | ${stats.brands} |
| Gates | ${stats.gates} |
| Merchants | ${stats.merchants} |
| Closed-loop cards | ${stats.closedLoopCards} |
| Choices | ${stats.choices} on ${stats.cardsWithChoices} cards (${stats.automaticChoices} automatic) |
| Cards with an issuer-stated value | ${stats.cardsWithStatedValue} |
| Brand-scoped rules | ${stats.brandScopedRules} |
| Rules excluding brands | ${stats.brandExcludingRules} |
| Rules on a chosen category | ${stats.choiceRules} |
| Gated rules | ${stats.gatedRules} |
| Rules requiring a payment path | ${stats.requiredPaymentPathRules} |
| Rules excluding a payment path | ${stats.excludedPaymentPathRules} |
| Dated (rotating or promotional) rules | ${stats.rotatingRules} |
| Dateless limited-time rules (all gated) | ${stats.datelessLimitedTimeRules} |
| Shared caps | ${stats.sharedCaps} |
| Rules with a spend cap / an unstated cap | ${stats.spendCapRules} / ${stats.unstatedCapRules} |
| Rules needing activation | ${stats.activationRules} |
| U.S.-merchant-only rules | ${stats.usOnlyRules} |

Rules by category: ${Object.entries(stats.rulesByCategory)
  .map(([category, count]) => `\`${category}\` ${count}`)
  .join(', ')}.

## Programs by valuation basis

"Cards" counts the cards whose value comes from that basis; ${stats.cardsByBasis['card-stated'] ?? 0} cards carry an
issuer-stated card value that overrides their program's.

${table(['Basis', 'Programs', 'Cards', 'Program IDs'], programRows)}

## Cards not in the catalog

Of the ${corpusIds.size + 7} candidate cards (${corpusIds.size} expansion corpus cards and the 7 real cards), ${corpusIds.size + 7 - catalog.cards.length} are held out by the
overlay. Separately, ${dropped.length} of the ${inputs.researched} researched expansion cards were dropped during verification and never entered
the corpus.

${table(
  ['Card', 'Stage', 'Reason'],
  [
    ...overlay.cards
      .filter((card) => card.heldOut)
      .map((card) => [`\`${card.cardId}\``, 'overlay', card.heldOut]),
    ...dropped.map((card) => [`\`${card.cardId}\``, 'verification', card.reason]),
  ],
)}

Rules held out by the overlay (not at retail, no v3 category, outside the U.S., and so on) are listed with their
reasons in \`catalog-overlay.json\`.

## Exclusions left out for the 25-word quote limit

Listed together, these corpus exclusions would repeat more than 25 consecutive capture words with the card's other
exclusions (general rule 22), so the catalog omits them; the corpus keeps them.

${table(
  ['Card', 'Omitted exclusion (start)'],
  Object.entries(QUOTE_LIMIT_OMISSIONS).flatMap(([cardId, starts]) =>
    starts.map((start) => [`\`${cardId}\``, `${start.split(' ').slice(0, 6).join(' ')} …`]),
  ),
)}

## Batches and dates

Built from \`evals/curation/catalog-batches.json\`, layers in order; a later layer's card replaces an earlier one's in
its place and new cards append (pipeline design, multi-batch builder).

${table(
  ['Layer', 'Kind', 'Directory', 'Corpus', 'Cards used', 'Replaced by a later layer'],
  inputs.layers.map((layer) => [
    `\`${layer.id}\``,
    layer.kind,
    `\`${layer.dir}\``,
    `\`${layer.corpusVersion}\``,
    String(layer.cards),
    String(layer.replaced.length),
  ]),
)}

- **verifiedAt** ${catalog.verifiedAt} is the newest date on which any of the ${dates.issuerSources} issuer sources the
  catalog cites was captured or re-checked (manifest \`checkedOn\`, else \`capturedOn\`); **expiresAt**
  ${catalog.expiresAt} is 30 days later. The oldest issuer source date is ${dates.oldest}; source dates:
  ${dates.captureDates.join(', ')}. Merchant MCC sources are not issuer terms and do not set the dates.

## Rule-ID continuity

Checked against \`evals/curation/rule-id-ledger.json\`, the append-only record of every rule ID issued (card and
SHA-256 of its terms) and the rule IDs of each catalog version. ${
  continuity.previous
    ? `Previous catalog: \`${continuity.previous.version}\` (${continuity.previous.rules} rules, ${n(continuity.previous.jsonBytes)} bytes JSON).`
    : 'Previous catalog: none (no other version in the ledger), so every rule ID counts as added.'
} This catalog: ${stats.rules} rules, ${n(stats.jsonBytes)} bytes JSON.

| Rule IDs | Count |
| --- | --- |
| Kept (same card, same terms) | ${continuity.kept.length} |
| Changed (terms changed, new ID issued) | ${continuity.changed.length} |
| Added | ${continuity.added.length} |
| Dropped | ${continuity.dropped.length} |
${
  continuity.changed.length
    ? `\n${table(
        ['Card', 'Previous ID', 'New ID'],
        continuity.changed.map((item) => [`\`${item.cardId}\``, `\`${item.from}\``, `\`${item.to}\``]),
      )}\n`
    : ''
}${continuity.dropped.length ? `\nDropped: ${continuity.dropped.map((id) => `\`${id}\``).join(', ')}.\n` : ''}`;

// A proposed build: the catalog, its report and what the ledger would gain, never the committed files. The ledger
// diff holds IDs, counts and versions only.
const issued = Object.keys(updatedLedger.ids).filter((id) => !inputs.ledger.ids[id]);
const proposed = proposedDir && [
  [new URL('catalog-v3.json', proposedDir), JSON.stringify(catalog) + '\n'],
  [reportOut, report],
  [
    new URL('ledger-diff.json', proposedDir),
    JSON.stringify(
      {
        schemaVersion: 1,
        version: catalog.version,
        config: args.config,
        previous: continuity.previous,
        rules: stats.rules,
        jsonBytes: stats.jsonBytes,
        kept: continuity.kept.length,
        changed: continuity.changed,
        added: continuity.added,
        dropped: continuity.dropped,
        idsIssued: issued,
      },
      null,
      2,
    ) + '\n',
  ],
];
const outputs = proposed || [
  [out, text],
  [reportOut, report],
  [ledgerOut, ledger],
];

if (args.check) {
  const stale = outputs.filter(([path, expected]) => {
    try {
      return readFileSync(path, 'utf8') !== expected;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(
      `${stale.map(([path]) => fileURLToPath(path).slice(fileURLToPath(root).length)).join(', ')} stale. Run npm run catalog:v3.`,
    );
    process.exit(1);
  }
  console.log(
    `Catalog v3 ${catalog.version} matches its inputs (${catalog.cards.length} cards, ${n(stats.jsonBytes)} bytes).`,
  );
} else if (proposed) {
  mkdirSync(proposedDir, { recursive: true });
  for (const [path, content] of proposed) writeFileSync(path, content);
  console.log(
    `Wrote the proposed catalog v3 ${catalog.version} with ${catalog.cards.length} cards (${n(stats.jsonBytes)} bytes), its build report and ledger diff to ${args['out-dir']}; nothing that ships changed.`,
  );
} else {
  for (const [path, content] of outputs) writeFileSync(path, content);
  console.log(
    `Wrote catalog v3 ${catalog.version} with ${catalog.cards.length} cards (${n(stats.jsonBytes)} bytes), the build report and the rule-ID ledger.`,
  );
}
