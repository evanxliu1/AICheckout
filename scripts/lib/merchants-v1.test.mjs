import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildMerchantRelease, merchantsModuleText } from './merchants-v1.mjs';

const config = { version: '2026-10-10.test.1', verifiedAt: '2026-10-10T00:00:00Z', sources: [] };
const record = (id, hosts, extra = {}) => ({
  id,
  name: id,
  hosts,
  kind: 'merchant',
  physicalGoods: true,
  category: 'general-merchandise',
  evidence: { basis: 'default', sourceIds: [] },
  brandIds: [],
  disabled: false,
  ...extra,
});

test('assembles a valid release with the records sorted by id', () => {
  const release = buildMerchantRelease(config, [
    record('zeta', ['zeta.example']),
    record('alpha', ['alpha.example']),
  ]);
  assert.equal(release.schemaVersion, 1);
  assert.equal(release.version, '2026-10-10.test.1');
  assert.deepEqual(
    release.merchants.map((m) => m.id),
    ['alpha', 'zeta'],
  );
});

test('rejects an invalid release naming every issue', () => {
  assert.throws(
    () => buildMerchantRelease(config, [record('a', ['shared.example']), record('b', ['shared.example'])]),
    /merchants: Hosts must be unique across merchants/,
  );
  assert.throws(
    () => buildMerchantRelease(config, [record('a', ['a.example'], { category: 'supermarkets' })]),
    /merchants\.0\.category: A category other than general-merchandise needs evidence/,
  );
});

test('writes a generated module that is not to be edited', () => {
  const text = merchantsModuleText(
    buildMerchantRelease(config, [
      record('pay', ['pay.example'], { kind: 'processor', physicalGoods: false }),
    ]),
  );
  assert.match(text, /^\/\/ Generated by scripts\/build-merchants-v1\.mjs/);
  assert.match(text, /1 records, 1 of them payment/);
  assert.match(text, /export const MERCHANTS_V1: MerchantRelease = \{"schemaVersion":1,/);
});
