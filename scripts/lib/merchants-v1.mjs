// Assembles a merchant release (schema `merchant-release.1`) from the committed records in evals/merchants/db/records/
// and the release header in evals/merchants/db/release-config.json, deterministically: records sorted by id, no model
// output. Used by scripts/build-merchants-v1.mjs; Phase 14.3 adds the pipeline that writes the records.
import { merchantReleaseSchema } from '../../packages/rewards-core/src/merchant-release.ts';

/** The release from the header and the record files' contents; throws with every Zod issue when it is invalid. */
export function buildMerchantRelease(config, records) {
  const release = {
    schemaVersion: 1,
    version: config.version,
    verifiedAt: config.verifiedAt,
    sources: config.sources,
    merchants: [...records].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)),
  };
  const result = merchantReleaseSchema.safeParse(release);
  if (!result.success)
    throw new Error(
      `The merchant release is invalid:\n- ${result.error.issues
        .map((issue) => `${issue.path.join('.') || '(release)'}: ${issue.message}`)
        .join('\n- ')}`,
    );
  return result.data;
}

/** The generated module text before formatting. */
export function merchantsModuleText(release) {
  const processors = release.merchants.filter((m) => m.kind === 'processor').length;
  return `// Generated by scripts/build-merchants-v1.mjs from evals/merchants/db/records/*.json and release-config.json.
// Do not edit; rerun \`npm run merchants\`. \`npm run merchants:check\` fails when this file is stale.
import type { MerchantRelease } from './types.ts';

/** The bundled merchant release (schema 1): ${release.merchants.length} records, ${processors} of them payment
 * processors, verified ${release.verifiedAt.slice(0, 10)}. The extension matches store websites against it on the
 * device and refreshes it from the hosted release when one is published. */
export const MERCHANTS_V1: MerchantRelease = ${JSON.stringify(release)};
`;
}
